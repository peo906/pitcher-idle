export const textWidth = (str, scale) => str.length * 6 * scale - scale;

export function drawPixelText(g, str, x, y, color, scale = 1) {
  g.fillStyle(color, 1);
  for (const ch of str) {
    const rows = G[ch] || G[' '];
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < 5; rx++) if (row[rx] === '1') g.fillRect(x + rx * scale, y + ry * scale, scale, scale);
    });
    x += 6 * scale;
  }
}
